"""
Writes src/lib/report/embeddedAssets.ts (npm run report:assets): the PDF's fonts and logo mark as base64 text.

Android's PDF maker renders an HTML string with no way to fetch files, and reading bundled assets back from disk
fails on release builds (their locations are not absolute paths), so the report carries its own bytes. Fonts are
cut down to Latin plus the symbols the report prints (rupee sign, minus, dashes, arrows); anything else falls back
to the phone's own font.
"""
import base64
import io
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / 'node_modules' / '@expo-google-fonts'
UNICODES = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [
    0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x20B9, 0x2192, 0x2212, 0x25CF,
]


def cut(path: Path) -> str:
    font = TTFont(path)
    options = subset.Options()
    options.layout_features = ['kern', 'liga', 'calt', 'locl', 'mark', 'mkmk']
    options.name_IDs = [1, 2, 3, 4, 6]
    options.notdef_outline = True
    sub = subset.Subsetter(options)
    sub.populate(unicodes=UNICODES)
    sub.subset(font)
    out = io.BytesIO()
    font.save(out)
    return base64.b64encode(out.getvalue()).decode()


def png(name: str) -> str:
    return base64.b64encode((ROOT / 'assets' / name).read_bytes()).decode()


def main():
    entries = {
        'fredoka': cut(FONTS / 'fredoka' / '600SemiBold' / 'Fredoka_600SemiBold.ttf'),
        'archivo': cut(FONTS / 'archivo' / '400Regular' / 'Archivo_400Regular.ttf'),
        'archivoBold': cut(FONTS / 'archivo' / '600SemiBold' / 'Archivo_600SemiBold.ttf'),
        'markCrescent': png('report-mark-crescent.png'),
        'markDot': png('report-mark-dot.png'),
    }
    lines = [
        '// Generated by scripts/generateReportAssets.py; do not edit by hand.',
        '// Fonts and logo mark for the PDF report, as base64, so the report never reads files at run time.',
        'export const REPORT_ASSETS = {',
    ]
    lines += [f"  {k}: '{v}'," for k, v in entries.items()]
    lines += ['} as const;', '']
    (ROOT / 'src' / 'lib' / 'report' / 'embeddedAssets.ts').write_text('\n'.join(lines))
    print({k: len(v) for k, v in entries.items()})


if __name__ == '__main__':
    main()
